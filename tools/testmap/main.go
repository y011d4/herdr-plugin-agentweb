// Command testmap turns node's JUnit test report into docs/go-migration/test-map.md:
// every TypeScript test, the server ones the Go port must reproduce (one t.Run with
// the same name each) and the ones that stay in TypeScript with the web UI.
//
//	set -o pipefail
//	node --test --test-reporter=junit 'server/test/*.test.ts' 'web/test/*.test.ts' \
//	  | go run ./tools/testmap > /tmp/test-map.md && mv /tmp/test-map.md docs/go-migration/test-map.md
//
// It refuses a report with no tests or with failures, so a broken run never
// replaces the map.
//
// The reporter, unlike a grep of the sources, sees names built in loops.
//
// With -check (check.go) it counts instead how many of the map's tests the Go
// port reproduces.
package main

import (
	"encoding/xml"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"
)

type test struct{ file, path string }

func main() {
	if len(os.Args) == 3 && os.Args[1] == "-check" {
		if err := check(os.Args[2], os.Stdin); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	tests, err := parse(os.Stdin)
	if err == nil && len(tests) == 0 {
		err = fmt.Errorf("no tests in the report")
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var port, keep []test
	for _, t := range tests {
		if strings.HasPrefix(t.file, "server/test/") && t.file != "server/test/prompt.test.ts" {
			port = append(port, t)
		} else {
			keep = append(keep, t)
		}
	}
	fmt.Println("# Test map: TypeScript → Go")
	fmt.Println()
	fmt.Println("Generated by `tools/testmap` (see its doc comment); don't edit by hand.")
	fmt.Println()
	fmt.Printf("- **To port to Go (N = %d):** the server's tests. Each becomes a `t.Run` with the same name (`describe › it` path), in P1/P2 of docs/go-migration-plan.md.\n", len(port))
	fmt.Printf("- **Stay in TypeScript (%d):** the web UI's tests, and `server/test/prompt.test.ts`, which tests `web/src/prompt.ts` (moves to `web/test/` in P5).\n", len(keep))
	fmt.Println()
	fmt.Printf("## To port to Go (%d)\n\n", len(port))
	table(port)
	fmt.Printf("\n## Stay in TypeScript (%d)\n\n", len(keep))
	table(keep)
}

// cell escapes what Markdown table cells would otherwise render as markup
var cell = strings.NewReplacer("|", `\|`, "&", "&amp;", "<", "&lt;", ">", "&gt;")

func table(ts []test) {
	fmt.Println("| # | file | test |")
	fmt.Println("|---|---|---|")
	for i, t := range ts {
		fmt.Printf("| %d | %s | %s |\n", i+1, t.file, cell.Replace(t.path))
	}
}

// parse walks the JUnit XML in document order, nesting testsuite names (describe
// blocks) into each testcase's path.
func parse(r io.Reader) ([]test, error) {
	wd, _ := os.Getwd()
	dec := xml.NewDecoder(r)
	var stack []string
	var out []test
	for {
		tok, err := dec.Token()
		if err == io.EOF {
			return out, nil
		}
		if err != nil {
			return nil, err
		}
		switch t := tok.(type) {
		case xml.StartElement:
			switch t.Name.Local {
			case "testsuite":
				stack = append(stack, attr(t, "name"))
			case "failure", "error":
				return nil, fmt.Errorf("the report has a failing test (%s)", strings.Join(stack, " › "))
			case "testcase":
				file, _ := filepath.Rel(wd, attr(t, "file"))
				out = append(out, test{file: file, path: strings.Join(append(append([]string{}, stack...), attr(t, "name")), " › ")})
			}
		case xml.EndElement:
			if t.Name.Local == "testsuite" && len(stack) > 0 {
				stack = stack[:len(stack)-1]
			}
		}
	}
}

func attr(e xml.StartElement, name string) string {
	for _, a := range e.Attr {
		if a.Name.Local == name {
			return a.Value
		}
	}
	return ""
}
