/** ui/Settings.tsx — #/settings: notifications, the connection, sign-out and the app's build. */
import { useEffect, useState, useSyncExternalStore } from 'react';
import { clearToken } from '../api.ts';
import { STORAGE_NOTIF } from '../notify.ts';
import { setAppState, store, subscribe } from '../store.ts';
import { wsSignOut } from '../ws.ts';

const APP_VERSION = '0.1.0';
// The built JS file's content hash (assets/index-<hash>.js), shown here and in the prompt
// panel, so a stale cached bundle is immediately visible. 'dev' unbuilt.
export const BUILD = import.meta.url.match(/-([\w-]{8})\.js$/)?.[1] ?? 'dev';

/** Back goes to `back`: the Home or list that opened Settings. */
export const settingsTopbar = (back: string) => ({
  title: 'Settings',
  left: <button className="topbar-back" aria-label="Back" onClick={() => { location.hash = back; }}>&#8592;</button>,
});

export function Settings({ toast, onSignedOut }: { toast: (title: string, body: string) => void; onSignedOut: () => void }) {
  const state = useSyncExternalStore(subscribe, () => store.appState);
  const wsConnected = useSyncExternalStore(subscribe, () => store.wsConnected);
  const [notif, setNotif] = useState(() => localStorage.getItem(STORAGE_NOTIF) === 'true');
  const [permission, setPermission] = useState(() => typeof Notification !== 'undefined' ? Notification.permission : 'unavailable');
  const [cache, setCache] = useState<string | null>(null);

  // The SW's cache (sw.js, generated by the build): a CSS-only change keeps BUILD but
  // renames the cache, so this tells whether the phone has the new build. caches.keys()
  // lists in creation order: the newest is a just-deployed build's, whose SW may still be
  // installing; controllerchange (that SW taking over) shows it again.
  useEffect(() => {
    const show = (): void => {
      (typeof caches === 'undefined' ? Promise.resolve([]) : caches.keys()).then(
        (keys) => setCache(keys.map((key) => /^herdr-yoicks-([0-9a-f]{8})$/.exec(key)?.[1]).filter(Boolean).at(-1) ?? '-'),
        () => setCache('-'));
    };
    show();
    const sw = navigator.serviceWorker; // absent outside a secure context
    sw?.addEventListener('controllerchange', show);
    return () => sw?.removeEventListener('controllerchange', show);
  }, []);

  const setNotifications = (on: boolean): void => {
    localStorage.setItem(STORAGE_NOTIF, on ? 'true' : 'false');
    setNotif(on);
  };
  const requestPermission = async (): Promise<void> => {
    if (typeof Notification === 'undefined') {
      toast('Not supported', 'Notifications are not available in this browser.');
      return;
    }
    const result = await Notification.requestPermission();
    setPermission(result);
    if (result === 'granted') setNotifications(true);
  };
  const signOut = (): void => {
    wsSignOut();
    setAppState(null);
    clearToken();
    onSignedOut();
  };

  return (
    <div id="screen-settings">
      <div className="settings-section">
        <div className="settings-section-title">Notifications</div>
        <div className="settings-row">
          <span className="settings-row-label">Enable notifications</span>
          <label className="toggle">
            <input type="checkbox" id="toggle-notif" checked={notif} onChange={(e) => setNotifications(e.target.checked)} />
            <span className="toggle-track"></span>
          </label>
        </div>
        <div className="settings-row">
          <span className="settings-row-label">Permission status</span>
          <span className="settings-row-value" id="notif-permission">{permission}</span>
        </div>
        <div className="settings-row">
          <button className="btn-secondary" id="btn-request-notif" style={{ width: '100%' }} onClick={() => { void requestPermission(); }}>Request Notification Permission</button>
        </div>
      </div>

      <div className="settings-section">
        <div className="settings-section-title">Connection</div>
        <div className="settings-row">
          <span className="settings-row-label">Bridge URL</span>
          <span className="settings-row-value">{`${location.protocol}//${location.host}`}</span>
        </div>
        <div className="settings-row">
          <span className="settings-row-label">herdr version</span>
          <span className="settings-row-value">{String(state?.herdr?.version ?? '—')}</span>
        </div>
        <div className="settings-row">
          <span className="settings-row-label">Protocol</span>
          <span className="settings-row-value">{String(state?.herdr?.protocol ?? '—')}</span>
        </div>
        <div className="settings-row">
          <span className="settings-row-label">WS status</span>
          <span className="settings-row-value">{wsConnected ? 'Connected' : 'Disconnected'}</span>
        </div>
      </div>

      <div className="settings-section">
        <div className="settings-section-title">Account</div>
        <div className="settings-row">
          <button className="btn-secondary" id="btn-clear-token" style={{ width: '100%', color: '#f47c2a' }} onClick={signOut}>Clear token &amp; sign out</button>
        </div>
      </div>

      <div className="settings-section">
        <div className="settings-section-title">About</div>
        <div className="settings-row">
          <span className="settings-row-label">App version</span>
          <span className="settings-row-value" id="app-version">{`${APP_VERSION} (${BUILD})${cache === null ? '' : ` cache ${cache}`}`}</span>
        </div>
      </div>
    </div>
  );
}
