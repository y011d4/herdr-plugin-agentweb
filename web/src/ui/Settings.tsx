/** ui/Settings.tsx — #/settings (in ui/SettingsSheet.tsx): notifications, the connection (the bridge, herdr and, with a
 *  headless orchestrator, the last Claude Code check), sign-out and the app's version and build. */
import { Button, Group, Image, Paper, Switch, Text } from '@mantine/core';
import { useEffect, useState, useSyncExternalStore, type ReactNode } from 'react';
import { clearToken } from '../api.ts';
import { STORAGE_NOTIF } from '../notify.ts';
import { setAppState, store, subscribe } from '../store.ts';
import type { ClaudeCheck } from '../types.ts';
import { wsSignOut } from '../ws.ts';
import { relativeTime } from './Dashboard.tsx';

// The built JS file's content hash (assets/index-<hash>.js), shown here and in the prompt
// panel, so a stale cached bundle is immediately visible. 'dev' unbuilt.
export const BUILD = import.meta.url.match(/-([\w-]{8})\.js$/)?.[1] ?? 'dev';

// the browser's notification permission (Notification.permission; 'unavailable': no such API), in words
const PERMISSION: Record<string, string> = {
  default: 'Not asked yet', granted: 'Allowed', denied: 'Blocked — change it in the browser settings', unavailable: 'Not available in this browser',
};

const CHECK_STALE_MS = 26 * 3_600_000; // the check runs a day apart at most: older means its timer is off

/** The last Claude Code check of headless mode (scripts/claude-canary.sh), in words: when none has
 *  run or the last is over a day old, its timer is off. */
export function claudeCheckText(c: ClaudeCheck | null, now: number): string {
  if (!c) return 'none yet: the periodic check is off (sh scripts/claude-canary.sh install, then enable its timer)';
  const result = c.ok ? 'passed' : `failed (${c.failed.join(', ')})`;
  const stale = now - c.at > CHECK_STALE_MS ? ': none since, the periodic check looks off' : '';
  return `${c.version} ${result}, ${relativeTime(c.at)}${stale}`;
}

export function Settings({ onSignedOut }: { onSignedOut: () => void }) {
  const state = useSyncExternalStore(subscribe, () => store.appState);
  const [notif, setNotif] = useState(() => localStorage.getItem(STORAGE_NOTIF) === 'true');
  const [permission, setPermission] = useState(() => typeof Notification !== 'undefined' ? Notification.permission : 'unavailable');
  const [cache, setCache] = useState<string | null>(null);
  const headless = state?.orchestrators?.some((o) => o.mode === 'headless');

  // The SW's cache (sw.js, generated by the build): a CSS-only change keeps BUILD but
  // renames the cache, so this tells whether the phone has the new build. caches.keys()
  // lists in creation order: the newest is a just-deployed build's, whose SW may still be
  // installing; controllerchange (that SW taking over) shows it again.
  useEffect(() => {
    const show = (): void => {
      (typeof caches === 'undefined' ? Promise.resolve([]) : caches.keys()).then(
        (keys) => setCache(keys.map((key) => /^herdr-yoicks-([0-9a-f]{8})$/.exec(key)?.[1]).filter(Boolean).at(-1) ?? '-'),
        () => setCache('-'));
    };
    show();
    const sw = navigator.serviceWorker; // absent outside a secure context
    sw?.addEventListener('controllerchange', show);
    return () => sw?.removeEventListener('controllerchange', show);
  }, []);

  // turned on before the browser has asked: it asks now (a tap, as it requires), and anything but a yes turns it back
  // off; the status row shows its answer
  const setNotifications = (on: boolean): void => {
    localStorage.setItem(STORAGE_NOTIF, on ? 'true' : 'false');
    setNotif(on);
    if (on && permission === 'default') {
      void Notification.requestPermission().then((result) => {
        setPermission(result);
        if (result !== 'granted') setNotifications(false);
      });
    }
  };
  const signOut = (): void => {
    wsSignOut();
    setAppState(null);
    clearToken();
    onSignedOut();
  };

  return (
    <div id="screen-settings" className="flex-1 overflow-y-auto px-4 pt-4 pb-[calc(var(--safe-bottom)+16px)]">
      <Section title="Notifications">
        <Row label="Enable notifications">
          <Switch id="toggle-notif" className="toggle" size="lg" withThumbIndicator={false} aria-label="Enable notifications" checked={notif} onChange={(e) => setNotifications(e.currentTarget.checked)} />
        </Row>
        <Row label="Permission status" value={PERMISSION[permission] ?? permission} valueId="notif-permission" />
      </Section>

      <Section title="Connection">
        <Row label="Bridge URL" value={`${location.protocol}//${location.host}`} />
        <Row label="herdr version" value={`${state?.herdr?.version ?? '—'}${state?.herdr?.protocol == null ? '' : ` (protocol ${state.herdr.protocol})`}`} />
        {headless && <Row label="Claude Code check" value={claudeCheckText(state?.claudeCheck ?? null, Date.now())} valueId="claude-check" />}
      </Section>

      <Section title="Account">
        <Row><Button id="btn-clear-token" variant="default" fullWidth fw={400} fz={14} c="blocked" onClick={signOut}>Clear token &amp; sign out</Button></Row>
      </Section>

      <Section title="About">
        <Row><Image src="/icons/lockup.svg" alt="Yoicks" h={28} w="auto" /></Row>
        <Row label="App version" value={`${state?.version ?? '—'} (${BUILD})${cache === null ? '' : ` cache ${cache}`}`} valueId="app-version" />
      </Section>
    </div>
  );
}

/** A group of rows on the surface, under its title in small capitals. */
function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <Paper className="settings-section overflow-hidden" withBorder radius={10} bg="dark.7" mb={20}>
      <Text className="settings-section-title border-b border-(--color-border)" px={16} py={10} bg="dark.6" fz={11} fw={600} c="dimmed" tt="uppercase" lts="0.08em">
        {title}
      </Text>
      {children}
    </Paper>
  );
}

/** A row: its label at the left, its value (or what is given) at the right; a rule between rows. The class names
 *  are the hooks e2e reads the rows by. */
function Row({ label, value, valueId, children }: { label?: string; value?: string; valueId?: string; children?: ReactNode }) {
  return (
    <Group className="settings-row min-h-11 border-b border-(--color-border) px-4 py-3.5 last:border-b-0" gap={12} wrap="nowrap">
      {label ? <Text className="settings-row-label" flex={1} fz={15}>{label}</Text> : null}
      {value !== undefined ? <Text className="settings-row-value" id={valueId} fz={13} c="dimmed">{value}</Text> : null}
      {children}
    </Group>
  );
}
